#include <stdio.h>
#include <math.h>

int main() {
    
    double a = 10.8;

    printf("%lf\n", ceil(a));

    printf("%lf\n", floor(a));

    printf("%lf\n", round(a));

    printf("%lf\n", sqrt(a));

    printf("%lf\n", sqrt(4));

    printf("%lf\n", pow(a ,4));

    printf("%lf\n", pow(4 ,4));




 
    return 0;
} 